package ai.arena.qatar.world;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Loads the committed synthetic world bundle through the real parsers.
 *
 * <p>The fixture is generated by {@code tools/selftest_game_world.py} and committed under
 * {@code core/src/test/resources/synthetic_world}, so these tests have real bundle bytes to chew on
 * (magic numbers, little-endian counts, delta-encoded coordinates, digests) without needing the 12 MB
 * country compile or a network fetch. The country bundle itself is validated in CI against this same
 * parser by {@code tools/validate_game_world.py}.
 */
final class WorldBundlesTest {

    private static final double ORIGIN_E = 553000.0;
    private static final double ORIGIN_N = 2796000.0;
    private static Path fixture;

    @BeforeAll
    static void locateFixture() {
        fixture = Paths.get("src/test/resources/synthetic_world");
        if (!Files.isDirectory(fixture)) {
            fixture = Paths.get("core/src/test/resources/synthetic_world");
        }
        assertTrue(Files.isDirectory(fixture), "synthetic world fixture is missing: " + fixture
                + " (run python3 tools/selftest_game_world.py)");
    }

    private static byte[] read(String name) throws IOException {
        return Files.readAllBytes(fixture.resolve(name));
    }

    private static BundleReader open(String name, String digest) throws IOException {
        byte[] raw = read(name);
        return BundleReader.open(name, raw, digest);
    }

    @Test
    @DisplayName("manifest declares the grid the geometry is expressed in")
    void manifest() throws IOException {
        String json = new String(read("manifest.json"), java.nio.charset.StandardCharsets.UTF_8);
        GameManifest manifest = GameManifest.parse(json);
        assertEquals(GameManifest.SUPPORTED_FORMAT, manifest.format);
        assertEquals("EPSG:32639", manifest.crs);
        assertEquals(ORIGIN_E, manifest.originEast, 1e-9);
        assertEquals(ORIGIN_N, manifest.originNorth, 1e-9);
        assertEquals(1600.0, manifest.widthM, 1e-9);
        assertEquals(1600.0, manifest.heightM, 1e-9);
        assertEquals(1, manifest.municipalities.size());
        assertEquals("Synthetic Municipality", manifest.municipalities.get(0).name);
        assertTrue(manifest.attribution.contains("OpenStreetMap"), "attribution must be present");
        assertEquals(1, manifest.spawnPoints.get("aeroplane"));
        assertTrue(manifest.describe().contains("buildings"), "summary mentions the world contents");
    }

    @Test
    @DisplayName("manifest digests are verified, and a corrupted bundle is rejected")
    void digestVerification() throws IOException {
        String json = new String(read("manifest.json"), java.nio.charset.StandardCharsets.UTF_8);
        GameManifest manifest = GameManifest.parse(json);
        assertFalse(manifest.buildings.sha256.isEmpty(), "fixture must carry a digest");

        byte[] corrupt = read(manifest.buildings.file);
        corrupt[corrupt.length / 2] ^= 0x5A;
        IllegalStateException error = assertThrows(IllegalStateException.class,
                () -> BundleReader.open("buildings", corrupt, manifest.buildings.sha256));
        assertTrue(error.getMessage().contains("SHA-256"), "the failure must name the digest problem");
    }

    @Test
    @DisplayName("buildings keep their real footprint shape, height and type")
    void buildings() throws IOException {
        String json = new String(read("manifest.json"), java.nio.charset.StandardCharsets.UTF_8);
        GameManifest manifest = GameManifest.parse(json);
        Buildings buildings = Buildings.parse(
                open(manifest.buildings.file, manifest.buildings.sha256), ORIGIN_E, ORIGIN_N);

        assertEquals(5, buildings.ringCount, "five footprint rings were packed");
        assertEquals(manifest.buildings.records, buildings.ringCount);

        int mosqueRing = -1;
        int towerRing = -1;
        for (int ring = 0; ring < buildings.ringCount; ring++) {
            if (buildings.type[ring] == Buildings.TYPE_MOSQUE) {
                mosqueRing = ring;
            }
            if (buildings.heightM[ring] > 100f) {
                towerRing = ring;
            }
        }
        assertTrue(mosqueRing >= 0, "the mosque must survive the round trip");
        assertEquals(Buildings.ROOF_DOME, buildings.roof[mosqueRing], "doomed roof shape is preserved");
        assertTrue(buildings.isLandmark(mosqueRing), "the mosque is flagged as a landmark");
        assertEquals(9.5f, buildings.heightM[mosqueRing], 1e-3f);
        assertTrue(buildings.areaM2(mosqueRing) > 1000.0, "a 40x30 m footprint is 1200 m2");

        assertTrue(towerRing >= 0, "the 120 m tower must survive");
        assertEquals(120.0f, buildings.heightM[towerRing], 1e-3f);

        // Real footprints, not bounding boxes: the L-shaped villa has six distinct corners.
        int lShaped = -1;
        for (int ring = 0; ring < buildings.ringCount; ring++) {
            if (buildings.ringLength[ring] == 7 && buildings.heightM[ring] < 8f) {
                lShaped = ring;
            }
        }
        assertTrue(lShaped >= 0, "the L-shaped footprint keeps its six corners plus the closure");
        assertTrue(buildings.areaM2(lShaped) < 30.0 * 30.0,
                "an L shape must be smaller than its bounding box, proving the shape was kept");
    }

    @Test
    @DisplayName("roads keep class, width, direction and bilingual names")
    void roads() throws IOException {
        Roads roads = Roads.parse(open("roads.bin.gz", ""));
        assertEquals(3, roads.count);

        int primary = -1;
        int oneWay = -1;
        for (int line = 0; line < roads.count; line++) {
            if (roads.roadClass[line] == 1) {
                primary = line;
            }
            if (roads.isOneWay(line)) {
                oneWay = line;
            }
        }
        assertTrue(primary >= 0, "the primary road is present");
        assertEquals(14.0f, roads.widthM[primary], 1e-3f);
        assertEquals(90, roads.speedKph[primary]);
        assertEquals(3, roads.lanes[primary]);
        assertEquals(1495.0, roads.lengthM(primary), 1.0);
        assertTrue(oneWay >= 0, "the one-way street keeps its direction flag");

        // Coordinates come back in the national frame relative to the manifest origin.
        float firstEast = roads.xz[roads.lineStart[primary] * 2];
        assertEquals(5.0, firstEast, 0.01);
        float firstNorth = roads.xz[roads.lineStart[primary] * 2 + 1];
        assertEquals(850.0, firstNorth, 0.01);
    }

    @Test
    @DisplayName("land use, water and barriers parse with their classes intact")
    void areasAndBarriers() throws IOException {
        String json = new String(read("manifest.json"), java.nio.charset.StandardCharsets.UTF_8);
        GameManifest manifest = GameManifest.parse(json);

        Areas landuse = Areas.parse(open(manifest.landuse.file, manifest.landuse.sha256), "QLU1");
        assertEquals(3, landuse.count);
        boolean vegetation = false;
        boolean urban = false;
        for (int ring = 0; ring < landuse.count; ring++) {
            if (landuse.kind[ring] == Areas.KIND_VEGETATION) {
                vegetation = true;
            }
            if (landuse.areaClass[ring] == 13) {
                urban = true;
            }
        }
        assertTrue(vegetation, "the farm polygon is vegetation");
        assertTrue(urban, "the urban pad polygon is classified");
        assertEquals(600.0 * 500.0, landuse.areaM2(0), 1.0);

        Areas water = Areas.parse(open(manifest.water.file, manifest.water.sha256), "QWA1");
        assertEquals(1, water.count);
        assertEquals(Areas.WATER_INLAND, water.kind[0], "the lake is inland water");
        assertTrue(water.contains(0, 1000.0, 400.0), "the lake contains its own centre");

        Barriers barriers = Barriers.parse(open(manifest.barriers.file, manifest.barriers.sha256));
        assertEquals(2, barriers.count);
        assertEquals(Barriers.KIND_WALL, barriers.kind[0]);
        assertEquals(2.4f, barriers.heightM[0], 1e-3f);
        assertEquals(340.0, barriers.xz[(barriers.lineStart[0] + 1) * 2]
                - barriers.xz[barriers.lineStart[0] * 2], 0.01);
    }

    @Test
    @DisplayName("points of interest include each vehicle spawn and are queryable")
    void points() throws IOException {
        String json = new String(read("manifest.json"), java.nio.charset.StandardCharsets.UTF_8);
        GameManifest manifest = GameManifest.parse(json);
        Points points = Points.parse(open(manifest.pois.file, manifest.pois.sha256));
        assertEquals(5, points.count);

        FeatureIndex index = new FeatureIndex(pointBounds(points), points.count, ORIGIN_E, ORIGIN_N,
                1600, 1600, 100);
        int car = points.nearest(Points.KIND_CAR, 150, 150, index, 5000);
        assertTrue(car >= 0, "the car spawn is found from its own neighbourhood");
        assertEquals(Points.CLASS_PARKING, points.poiClass[car]);

        int plane = points.nearest(Points.KIND_PLANE, 0, 1600, index, 5000);
        assertTrue(plane >= 0, "the runway spawn is found");
        assertEquals(90.0f, points.facingDeg[plane], 0.01f, "runway heading is preserved");

        int none = points.nearest(Points.KIND_BOAT, 0, 0, index, 10);
        assertEquals(-1, none, "a spawn further away than the range is not returned");
    }

    private static float[] pointBounds(Points points) {
        float[] bounds = new float[points.count * 4];
        for (int i = 0; i < points.count; i++) {
            bounds[i * 4] = points.xz[i * 2];
            bounds[i * 4 + 1] = points.xz[i * 2 + 1];
            bounds[i * 4 + 2] = points.xz[i * 2];
            bounds[i * 4 + 3] = points.xz[i * 2 + 1];
        }
        return bounds;
    }

    @Test
    @DisplayName("the spatial index answers region queries without scanning everything")
    void featureIndex() throws IOException {
        String json = new String(read("manifest.json"), java.nio.charset.StandardCharsets.UTF_8);
        GameManifest manifest = GameManifest.parse(json);
        Buildings buildings = Buildings.parse(
                open(manifest.buildings.file, manifest.buildings.sha256), ORIGIN_E, ORIGIN_N);
        FeatureIndex index = new FeatureIndex(buildings.bounds, buildings.ringCount, ORIGIN_E,
                ORIGIN_N, 1600, 1600, 100);

        int[] nearMosque = index.collect(240, 280, 300, 320);
        assertTrue(nearMosque.length >= 1, "the mosque is found by a small query box");
        boolean mosqueFound = false;
        for (int id : nearMosque) {
            mosqueFound |= buildings.type[id] == Buildings.TYPE_MOSQUE;
        }
        assertTrue(mosqueFound, "the query returns the mosque, not something else");

        int[] empty = index.collect(5000, 5000, 5100, 5100);
        assertEquals(0, empty.length, "a query outside the data finds nothing");

        int[] everything = index.collect(0, 0, 1600, 1600);
        assertEquals(buildings.ringCount, everything.length, "a whole-world query finds every ring");
    }

    @Test
    @DisplayName("the string table carries bilingual names")
    void strings() throws IOException {
        StringTable table = StringTable.parse(BundleReader.open("strings", read("strings.bin.gz"),
                "").payloadBytes());
        assertTrue(table.size() > 0, "the table is populated");
        boolean english = false;
        boolean arabic = false;
        for (int i = 0; i < table.size(); i++) {
            String value = table.get(i);
            english |= "Corniche Street".equals(value);
            arabic |= value.contains("الكورنيش");
        }
        assertTrue(english, "English names are present");
        assertTrue(arabic, "Arabic names are present and keep their logical order");
        assertEquals("", table.get(0xFFFF), "a missing index returns an empty string, never null");
    }

    @Test
    @DisplayName("a bundle that is not a bundle is rejected, not misread")
    void rejectsGarbage() {
        byte[] garbage = new byte[64];
        BundleReader reader = BundleReader.ofRaw("garbage", garbage);
        assertThrows(IllegalStateException.class, () -> reader.header("QBG1"));
        assertNotNull(BundleReader.ofRaw("empty", new byte[0]));
    }

    @Test
    @DisplayName("resources are readable from the classpath too (packaging sanity)")
    void classpathReadable() throws IOException {
        try (InputStream stream = getClass().getResourceAsStream("/synthetic_world/manifest.json")) {
            assertNotNull(stream, "test resources must be on the classpath for the packaged build");
            assertTrue(new String(stream.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8)
                    .contains("\"format\""));
        }
    }
}
